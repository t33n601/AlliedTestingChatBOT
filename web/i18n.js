  /* plural nouns: en one/other, ru one/few/many, ro one/few/"de" */
  const PLURALS = {
    en: { source: ["source", "sources"], chunk: ["chunk", "chunks"], question: ["question", "questions"], document: ["document", "documents"], chat: ["chat", "chats"] },
    ru: { source: ["источник", "источника", "источников"], chunk: ["фрагмент", "фрагмента", "фрагментов"], question: ["вопрос", "вопроса", "вопросов"], document: ["документ", "документа", "документов"], chat: ["чат", "чата", "чатов"] },
    ro: { source: ["sursă", "surse", "de surse"], chunk: ["fragment", "fragmente", "de fragmente"], question: ["întrebare", "întrebări", "de întrebări"], document: ["document", "documente", "de documente"], chat: ["conversație", "conversații", "de conversații"] },
  };
  function form(lang, n) {
    if (lang === "ru") {
      const a = n % 10, b = n % 100;
      return a === 1 && b !== 11 ? 0 : a >= 2 && a <= 4 && (b < 10 || b >= 20) ? 1 : 2;
    }
    if (lang === "ro") return n === 1 ? 0 : n === 0 || (n % 100 >= 1 && n % 100 <= 19) ? 1 : 2;
    return n === 1 ? 0 : 1;
  }

  let lang = "en";
  try { lang = (JSON.parse(localStorage.getItem("kb.prefs") || "{}").lang) || "en"; } catch { /* default */ }
  if (!LANGS[lang]) lang = "en";
  const DICT = { en: {}, ru: RU, ro: RO }[lang];

  const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m)) : s);
  const t = (key, vars) => fill(DICT[key] != null ? DICT[key] : key, vars);
  /* "5 chunks" with the right plural form for the interface language */
  const pl = (n, noun) => `${n} ${PLURALS[lang][noun][form(lang, n)]}`;

  /* translate the static page: text nodes and the attributes people read */
  const norm = (s) => s.replace(/\s+/g, " ").trim();
  function apply(root) {
    if (lang === "en") return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.parentElement && n.parentElement.closest("script, style, code, [data-no-i18n]") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((n) => {
      const key = norm(n.nodeValue);
      if (!key || DICT[key] == null) return;
      const lead = n.nodeValue.match(/^\s*/)[0], trail = n.nodeValue.match(/\s*$/)[0];
      n.nodeValue = lead + DICT[key] + trail;
    });
    root.querySelectorAll("[placeholder], [title], [aria-label]").forEach((e) => {
      ["placeholder", "title", "aria-label"].forEach((a) => {
        const v = e.getAttribute(a);
        if (v && DICT[norm(v)] != null) e.setAttribute(a, DICT[norm(v)]);
      });
    });
  }

  document.documentElement.lang = lang;
  apply(document.body);
  window.KB_I18N = { lang, langs: LANGS, locale: LOCALES[lang], t, pl, apply };
